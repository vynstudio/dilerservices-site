"""Writes v3/assets/css/diler-v3.css: every colour and font in the Consultore stylesheets remapped to
Brand Kit v3 (generated part), followed by brand_hand.css (hand-written part)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); V = os.path.dirname(HERE)
CSS = os.path.join(V, 'assets', 'css')
DARK, DENIM, BLUE, SAND = '#1E2B40', '#395278', '#346BB5', '#7A6650'
LIGHT, LINE, MUTED, TEXT, SKY, SKY2 = '#F3F5F7', '#D5DAE1', '#646B6C', '#1F2430', '#E4EDFD', '#EFF4FE'
MAP = {  # template hex -> (background, text, border)
 '0e1124': (DARK, TEXT, LINE), '10002b': (DARK, DARK, DARK), '0b0a23': (DARK, DARK, DARK), '161540': (DARK, DARK, DARK),
 '131731': (DARK, DARK, DARK), '142329': (DARK, DARK, DARK), '2a0072': (BLUE, BLUE, BLUE), '03256c': (DENIM, DENIM, DENIM),
 'd4aeff': (SKY, BLUE, BLUE), 'dfc8f8': (SKY2, BLUE, LINE), 'fede65': (SKY, BLUE, BLUE), 'ffe456': (SKY, BLUE, BLUE),
 'ff3e55': (BLUE, BLUE, BLUE), 'fc0c0c': (BLUE, BLUE, BLUE), 'ff2424': (BLUE, BLUE, BLUE), 'ff9c00': (SAND, SAND, SAND),
 '00bf71': (BLUE, BLUE, BLUE), '03a600': (BLUE, BLUE, BLUE), '47494e': (MUTED, MUTED, LINE), '656565': (MUTED, MUTED, LINE),
 'f3f3f3': (LIGHT, MUTED, LINE), 'f4f4f4': (LIGHT, MUTED, LINE),
}
BG = {'background', 'background-color'}; TX = {'color', 'fill', 'stroke'}
HEX = re.compile(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b')
FONTS = re.compile(r'(Catamaran|DM Serif Display|"Inter"|Inter)', re.I)
def norm(h): h = h.lower(); return ''.join(c * 2 for c in h) if len(h) == 3 else h
def parse(css):
    i, n, stack, out = 0, len(css), [], []
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        head = css[i:j].strip()
        head = re.sub(r'/\*.*?\*/', '', head, flags=re.S).strip()
        if head.startswith('@media') or head.startswith('@supports'):
            stack.append(head); i = j + 1; continue
        if head.startswith('@'):
            d, k = 1, j + 1
            while k < n and d:
                d += {'{': 1, '}': -1}.get(css[k], 0); k += 1
            i = k; continue
        k = css.find('}', j); out.append((' '.join(stack), head, css[j + 1:k])); i = k + 1
        while i < n and css[i] in '} \n\t\r':
            if css[i] == '}' and stack: stack.pop()
            i += 1
    return out
rules, seen = [], set()
for f in ['typography.css', 'comon.css', 'master.css']:
    css = re.sub(r'/\*.*?\*/', '', open(os.path.join(CSS, f), encoding='utf-8').read(), flags=re.S)
    for media, sel, body in parse(css):
        if not sel or sel.startswith(':root'): continue
        decls = []
        for d in body.split(';'):
            if ':' not in d: continue
            prop, val = d.split(':', 1); prop = prop.strip().lower(); val = val.replace('!important', '').strip()
            if prop == 'font-family':
                if FONTS.search(val): decls.append((prop, '"Inter Variable", Inter, system-ui, sans-serif'))
                continue
            kind = 0 if prop in BG else 1 if prop in TX else 2
            hit = []
            def sub(m, kind=kind, hit=hit):
                h = norm(m.group(1))
                if h in MAP: hit.append(1); return MAP[h][kind]
                return m.group(0)
            nv = HEX.sub(sub, val)
            if hit: decls.append((prop, nv))
        if not decls: continue
        key = (media, sel, tuple(decls))
        if key in seen: continue
        seen.add(key); rules.append((media, sel, decls))
def pre(sel): return ','.join('html.ds-v3 ' + s.strip() if not s.strip().startswith('html') else s.strip().replace('html', 'html.ds-v3', 1) for s in sel.split(',') if s.strip())
out = ['/* Diler Services, Brand Kit v3 (Folio) on Consultore. Generated by _build/brand_css.py: do not edit above the hand rules. */',
       '@font-face{font-family:"Inter Variable";src:url(../fonts/inter/inter-latin-wght-normal.woff2) format("woff2");font-weight:100 900;font-style:normal;font-display:swap;unicode-range:U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD}',
       '@font-face{font-family:"Inter Variable";src:url(../fonts/inter/inter-latin-ext-wght-normal.woff2) format("woff2");font-weight:100 900;font-style:normal;font-display:swap;unicode-range:U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF}']
for media, sel, decls in rules:
    r = f'{pre(sel)}{{' + ';'.join(f'{p}:{v}!important' for p, v in decls) + '}'
    out.append(f'{media}{{{r}}}' if media else r)
hand = open(os.path.join(HERE, 'brand_hand.css'), encoding='utf-8').read()
open(os.path.join(CSS, 'diler-v3.css'), 'w', encoding='utf-8').write('\n'.join(out) + '\n' + hand)
print('generated rules', len(rules))
