import postcss from 'postcss'; import fs from 'fs';
const P=JSON.parse(fs.readFileSync('/workspace/consult/palettes/pal.json','utf8'));
const root='/workspace/diler-consult/assets/css/';
// old brand color -> palette role
const MAP={'0021a5':'primary','001466':'dark','0b2a9e':'input','f7b5cd':'soft','fa4616':'accent','c2340a':'accent','b8336a':'logo','fce3ec':'tint','fdf1f5':'tint','e3e8fa':'tint2','fff8f0':'light','231f20':'text','5e5a5b':'muted','e8e1da':'border','f3e9ee':'tint','fc7632':'accent'};
const VARS={blue:'primary',night:'dark',pink:'soft',citrus:'accent',deep:'accent',ink:'text',sand:'light',drift:'muted',shell:'border',hib:'logo','main-color':'primary','main-text-color':'dark','secondary-color':'primary'};
const re=new RegExp('#('+Object.keys(MAP).join('|')+')\\b','gi');
const seen=new Set();let rules=[];
for(const f of ['home.min.css','inner.min.css']){
  const ast=postcss.parse(fs.readFileSync(root+f,'utf8'));
  ast.walkRules(r=>{ if(r.parent.type==='atrule'&&/keyframes/.test(r.parent.name))return;
    const decls=[];r.walkDecls(d=>{ if(re.test(d.value)){re.lastIndex=0;decls.push(d)} re.lastIndex=0;});
    if(!decls.length)return;
    const media=r.parent.type==='atrule'?'@'+r.parent.name+' '+r.parent.params:'';
    const key=media+r.selector+decls.map(d=>d.prop+d.value).join();if(seen.has(key))return;seen.add(key);
    rules.push({media,sel:r.selector,decls:decls.map(d=>[d.prop,d.value,d.important])});});
}
let out='/* Palette previews. Generated by palettes.mjs from pal.json. Loaded only with ?palette=a|b|c. Default site is unchanged. */\n';
for(const [k,p] of Object.entries(P)){
  out+=`html.pal-${k}{`+Object.entries(VARS).map(([v,r])=>`--${v}:${p[r]}`).join(';')+'}\n';
  for(const r of rules){
    const sel=r.sel.split(',').map(s=>{s=s.trim();return /^(html|:root)/.test(s)?s.replace(/^(html|:root)/,`html.pal-${k}`):`html.pal-${k} ${s}`}).join(',');
    const body=r.decls.map(([pr,v,imp])=>`${pr}:${v.replace(re,(m,h)=>p[MAP[h.toLowerCase()]])}${imp?'!important':''}`).join(';');
    const rule=`${sel}{${body}}`;
    out+=r.media?`${r.media}{${rule}}\n`:rule+'\n';
  }
  // gradients that use rgba of the blue/pink in the hero
  out+=`html.pal-${k} .welcome2-section-area{background:radial-gradient(60% 70% at 80% 30%,${p.tint} 0,transparent 60%),radial-gradient(50% 60% at 10% 90%,${p.tint2} 0,transparent 60%),${p.light}!important}\n`;
}
fs.writeFileSync(root+'palettes.css',out);console.log(rules.length,'rules',out.length,'bytes');
